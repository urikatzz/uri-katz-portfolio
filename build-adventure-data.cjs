// Refresh the adventure's game catalog from the classic portfolio.
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('dist/index.html', 'utf8');
const app = fs.readFileSync('dist/app.js', 'utf8');
const personal = vm.runInNewContext(app.slice(0, app.indexOf('const artworks')) + ';projects');
const text = value => value.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').trim();
const companies = [...html.matchAll(/<article class="company-project[\s\S]*?<\/article>/g)].map(([article]) => ({
  title: text(article.match(/<h3>(.*?)<\/h3>/)[1]),
  platform: text(article.match(/<p class="company-platform">(.*?)<\/p>/)[1]),
  image: (article.match(/class="company-title"><img src="([^"]+)"/) || article.match(/<div class="company-media[^"]*">[\s\S]*?<img src="([^"]+)"/))[1],
  description: text(article.match(/class="company-platform">.*?<\/p><p>(.*?)<\/p>/)[1]),
  links: [...article.matchAll(/<a class="store-link" href="([^"]+)"[^>]*>(.*?)<\/a>/g)].map(([,url,label]) => [text(label).replace(' ↗',''),url]),
  category: 'COMPANY GAME'
}));
const featured = html.match(/<article class="featured">([\s\S]*?)<\/article>/)[1];
const games = [
  ...companies,
  {title:'Flocking Simulation', platform:'PC / UNITY ECS', image:'assets/flocking.png', description:'A flocking simulation built with Unity ECS, bringing 12,000 fish together in motion.',links:[['Download for PC',featured.match(/href="([^"]+)"/)[1]]]},
  ...personal.map(p=>({...p,image:'assets/'+p.image}))
].reverse().map(p=>({...p,category:p.category || 'PERSONAL GAME'}));
fs.writeFileSync('dist/adventure-data.js', '/* Generated by node build-adventure-data.cjs from the classic portfolio. */\nexport const games = '+JSON.stringify(games,null,2)+';\n');
console.log(`Synced ${games.length} games.`);

